"""Ingestors for NCEP BUFR tanks (``bAAA/xxBBB``).

The BUFR tank reader looks up ingestors by ID in this order:

1. ``bufr_tank/bAAA/xxBBB``: a tank-specific ingestor. One is registered for every
   mapping in configs/bufr/tanks, generated by dev/ush/generate_bufr_tank_yamls.py.
2. ``bufr_tank/<dataset>``: a per-dataset ingestor from table_a_mapping.yaml.

TODO(step 5): attach BufrTankInfo metadata (category, subtype, format, restricted)
  to each observation before storing.
"""

import glob
import logging
import os

import bufr
import numpy as np
import xarray as xr
import yaml

from geode.configs.config_path import PackageConfigDir
from geode.configs.table_a_mapping import BufrTankInfo
from geode.data.keys import LocationKey
from geode.ingest.ingestors import register
from geode.ingest.ingestors.base_ingestor import BaseIngestor
from geode.ingest.ingestors.bufr_ingestor import container_to_xarray

logger = logging.getLogger(__name__)

TanksConfigDir = os.path.join(PackageConfigDir, "bufr", "tanks")

RawReportPieces = "rawReportString"
RawReportDimension = "RawReportChunk"
RawReportPieceLength = 8


class BufrTankIngestor(BaseIngestor):
    """Base class for BUFR tank ingestors; stores data under the mapped dataset name."""

    def __init__(self, tank_info: BufrTankInfo):
        super().__init__(tank_info.dataset)
        self.tank_info = tank_info

    def _process(self, file_path: str) -> xr.DataTree | dict[str, xr.DataTree]:
        raise NotImplementedError(
            f"No decoding implemented yet for BUFR tank {self.tank_info.tank_id}"
        )


def level_variables(yaml_path: str) -> list[str]:
    """Return the encoder names of variables inside the ``group_by_variable`` sequence."""
    with open(yaml_path) as yaml_file:
        config = yaml.safe_load(yaml_file)

    group_key = config["bufr"].get("group_by_variable")
    if group_key is None:
        return []

    variables = config["bufr"]["variables"]
    prefix = variables[group_key]["query"].rsplit("/", 1)[0] + "/"
    sources = {
        name
        for name, definition in variables.items()
        if str(definition.get("query", "")).startswith(prefix)
    }
    return [
        entry["name"]
        for entry in config["encoder"]["variables"]
        if entry["source"].split("/")[-1] in sources
    ]


def _has_value(data: xr.DataArray) -> xr.DataArray:
    present = data.notnull()
    if data.dtype.kind in "OUS":
        present = present & (data != "")
    other_dims = [dim for dim in present.dims if dim != LocationKey]
    return present.any(dim=other_dims) if other_dims else present


def drop_empty_rows(
    datasets: dict[str, xr.Dataset], level_names: list[str]
) -> dict[str, xr.Dataset]:
    """Remove rows where every variable from the grouped sequence is missing.

    ``group_by_variable`` pads each report to the longest report in the file. A row is
    only removed when all of its level values are missing, so a level with a missing
    coordinate but real data is kept.
    """
    keep = None
    for full_name in level_names:
        group, name = full_name.rsplit("/", 1)
        dataset = datasets.get(f"/{group}")
        if dataset is None or name not in dataset:
            continue
        present = _has_value(dataset[name]).values
        keep = present if keep is None else keep | present

    if keep is None:
        return datasets

    indices = np.flatnonzero(keep)
    return {
        path: dataset.isel({LocationKey: indices})
        if LocationKey in dataset.dims
        else dataset
        for path, dataset in datasets.items()
    }


def join_raw_report(datasets: dict[str, xr.Dataset]) -> dict[str, xr.Dataset]:
    """Replace raw report text pieces with a single ``MetaData/rawReport`` string."""
    meta = datasets.get("/MetaData")
    if meta is None or RawReportPieces not in meta:
        return datasets

    if RawReportDimension not in meta[RawReportPieces].dims:
        # No pieces to join: an empty file, or a tank that does not carry raw text but
        # shares a dataset with one that does. The variable must still exist.
        empty = np.full(meta.sizes[LocationKey], "", dtype=object)
        return {
            **datasets,
            "/MetaData": meta.drop_vars(RawReportPieces).assign(
                rawReport=(LocationKey, empty, {"long_name": "Raw Report"})
            ),
        }

    pieces = meta[RawReportPieces].transpose(LocationKey, RawReportDimension).values
    joined = [
        "".join(
            (piece if isinstance(piece, str) else "").ljust(RawReportPieceLength)
            for piece in row
        ).rstrip()
        for row in pieces
    ]

    result = dict(datasets)
    result["/MetaData"] = meta.drop_vars(RawReportPieces).assign(
        rawReport=(
            LocationKey,
            np.array(joined, dtype=object),
            {"long_name": "Raw Report"},
        )
    )
    root = result.get("/")
    if root is not None and RawReportDimension in root.variables:
        result["/"] = root.drop_vars(RawReportDimension)
    return result


def use_variable_length_strings(
    datasets: dict[str, xr.Dataset],
) -> dict[str, xr.Dataset]:
    """Store strings as variable length so files with different lengths can append.

    Decoded strings have a fixed width set by the longest value in that file, and the
    Zarr store rejects an append when the width differs from what it already holds.
    """
    result = {}
    for path, dataset in datasets.items():
        updates = {}
        for name, data in dataset.data_vars.items():
            if data.dtype.kind in "US":
                converted = data.astype(object)
                converted.encoding = {
                    key: value for key, value in data.encoding.items() if key != "dtype"
                }
                updates[name] = converted
        result[path] = dataset.assign(updates) if updates else dataset
    return result


def finalize_tree(tree: xr.DataTree, level_names: list[str]) -> xr.DataTree | None:
    """Apply tank post-processing. Returns None when no observations remain."""
    datasets = {node.path: node.to_dataset(inherit=False) for node in tree.subtree}
    datasets = join_raw_report(drop_empty_rows(datasets, level_names))
    datasets = use_variable_length_strings(datasets)

    if datasets["/"].sizes.get(LocationKey, 0) == 0:
        return None
    return xr.DataTree.from_dict(datasets)


class MappedBufrTankIngestor(BufrTankIngestor):
    """Decode a tank using its mapping from configs/bufr/tanks."""

    def __init__(self, tank_info: BufrTankInfo):
        super().__init__(tank_info)
        file_name = f"{tank_info.tank_id.replace('/', '_')}.yaml"
        self.bufr_yaml = os.path.join(TanksConfigDir, file_name)

    def _process(self, file_path: str) -> xr.DataTree | dict[str, xr.DataTree]:
        # No table path: tanks carry their own NCEP tables, and passing one selects
        # the WMO reader, which finds no messages in them.
        container = bufr.Parser(file_path, self.bufr_yaml).parse()
        decoded = container_to_xarray(
            container, bufr.encoders.Description(self.bufr_yaml)
        )
        level_names = level_variables(self.bufr_yaml)

        trees = decoded if isinstance(decoded, dict) else {None: decoded}
        finished = {
            category: finalize_tree(tree, level_names)
            for category, tree in trees.items()
        }
        kept = {k: tree for k, tree in finished.items() if tree is not None}
        if not kept:
            logger.warning(
                f"No observations decoded from {file_path} for BUFR tank "
                f"{self.tank_info.tank_id}"
            )
            return {}
        return kept.get(None, kept)


for mapping_path in sorted(glob.glob(os.path.join(TanksConfigDir, "*.yaml"))):
    tank_name = os.path.basename(mapping_path)[: -len(".yaml")]
    register(f"bufr_tank/{tank_name.replace('_', '/')}")(MappedBufrTankIngestor)
